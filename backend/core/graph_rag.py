from datetime import datetime
from typing import TypedDict, List, Optional, Any

from langgraph.graph import StateGraph, START, END
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_google_genai import ChatGoogleGenerativeAI
from .rag_service import get_vectorstore

"""
Step 1: Defining the Graph State Schema

The first step in any LangGraph pipeline is specifying the data structure passed between your nodes.
Create a TypedDict representing everything needed during a single turn:

"""
class RAGState(TypedDict):
    # Inputs (Provided by caller)
    user_id: int
    document_id: int
    filename: str
    question: str
    selected_context: Optional[str]
    
    # Node Outputs
    documents: List[str]      # Chunks to feed into prompt
    sources: List[dict]       # Formatted source references with scores
    answer: str               # Output text generated by LLM

  
"""
Step 2: Creating the Worker Nodes

Each node is a pure function that takes state: RAGState and returns a dictionary updating specific keys.

Node 1: retrieve_node
Responsibility: Query ChromaDB with user/document metadata isolation and calculate relevance scores.
Reads: question, selected_context, user_id, document_id, filename.
Writes: documents, sources.
"""

def retrieve_node(state: RAGState) -> dict:
    """
    Retrieve node for RAG (Retrieval-Augmented Generation) process.
    
    Args:
        state (RAGState): The current state of the RAG process.
    """
    vectorstore = get_vectorstore()
    question = state['question']
    focus_text = (state.get('selected_context')or "").strip()


    # Formulate effective search query
    search_query = f"{question} {focus_text[:200]}" if focus_text else question

    # strict multi-tenant isolations

    scored_docs  = vectorstore.similarity_search_with_relevance_scores(
        search_query,
        k=4,
        filter={
            "$and": [
                {"user_id": state['user_id']},
                {"document_id": state['document_id']}
            ]
        }
    )

    context_chunks = []
    sources = []

    # Priority 1: User-highlighted text from PDF viewer
    if focus_text:
        context_chunks.append(f"--- USER HIGHLIGHTED TEXT ---\n{focus_text}")
        sources.append({
            "id": "Selected Text",
            "content": focus_text,
            "source": "User Selection",
            "match": "Focus"
        })

     # Priority 2: Vector store chunks

    for i, (doc, score) in enumerate(scored_docs):
        context_chunks.append(doc.page_content)
        sources.append({
            "id": i + 1,
            "content": doc.page_content,
            "source": doc.metadata.get("source", state["filename"]),
            "match": f"{max(10, min(99, int(score * 100)))}%"
        })

    return {
        "documents": context_chunks,    
        "sources": sources
    }

"""
Node 2: generate_node
Responsibility: Combine retrieved context with the question, format the prompt, and invoke Gemini.
Reads: documents, question.
Writes: answer.

"""

def generate_node(state: RAGState) -> dict:
    """
    Generate node for RAG (Retrieval-Augmented Generation) process.
    
    Args:
        state (RAGState): The current state of the RAG process.
    """
    docs = state.get("documents", [])
    question = state["question"]

    if not docs:
        return {"answer": "No relevant context found to answer the question."}

    # Combine retrieved documents into a single context string
    formatted_context = "\n\n".join(docs)

    now = datetime.now()
    current_date = now.strftime("%B %d, %Y")
    current_year = str(now.year)

    rag_chain = rag_prompt | generator_llm | StrOutputParser()
    answer_text = rag_chain.invoke({
        "context": formatted_context,
        "question": question,
        "current_date": current_date,
        "current_year": current_year
    })
    return {
        "answer": answer_text
    }


rag_prompt = ChatPromptTemplate.from_template(
    """You are an expert document assistant.
CURRENT DATE: {current_date} (Year: {current_year}).
CRITICAL TEMPORAL CONTEXT: The current real-world year is {current_year}. When reviewing documents, resumes, work experience, timelines, or dates, always evaluate them relative to {current_year}. Dates up to and including {current_year} (e.g. 2024, 2025, {current_year}) are valid past or present dates, not future dates. Never claim or assume that the current year is 2024 or earlier.

Answer the question accurately and thoroughly based only on the context below.
If you cannot answer the question using the context, state that clearly.

Context:
{context}

Question:
{question}

Answer:"""
)

generator_llm = ChatGoogleGenerativeAI(
    model="gemini-3.1-flash-lite",
    temperature=0.2,
    max_output_tokens=2048
)


def build_rag_graph():
    """
    Build the RAG (Retrieval-Augmented Generation) graph.
    
    Returns:
        StateGraph: The constructed RAG graph.
    """
    workflow = StateGraph(RAGState)
    # 2. Add nodes
    workflow.add_node("retrieve", retrieve_node)
    workflow.add_node("generate", generate_node)
    # 3. Add edges (Start -> Retrieve -> Generate -> End)
    workflow.add_edge(START, "retrieve")
    workflow.add_edge("retrieve", "generate")
    workflow.add_edge("generate", END)
    # 4. Compile graph
    return workflow.compile()

# Instantiate compiled runnable
rag_graph = build_rag_graph()

